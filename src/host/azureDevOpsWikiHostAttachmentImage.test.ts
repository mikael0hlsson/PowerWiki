import { beforeEach, describe, expect, it, vi } from "vitest";
import type { AzureDevOpsWikiHost as AzureDevOpsWikiHostType } from "./azureDevOpsWikiHost";

const getAccessToken = vi.fn();
const getService = vi.fn();
const fetchMock = vi.fn();

vi.mock("azure-devops-extension-sdk", () => ({
  getAccessToken: () => getAccessToken(),
  getService: (id: string) => getService(id),
}));

const { AzureDevOpsWikiHost } = await import("./azureDevOpsWikiHost");

const CONTEXT = {
  organizationName: "org",
  projectName: "PowerWiki",
  projectId: "adf21ddb-12ae-4355-924a-8121484e984e",
  userDisplayName: "Test",
};

const WIKI = {
  id: "wiki-id",
  name: "Product.wiki",
  repositoryId: "repo-id",
  repositoryRemoteUrl: "https://dev.azure.com/org/PowerWiki/_git/Product.wiki",
};

beforeEach(() => {
  getAccessToken.mockReset();
  getService.mockReset();
  fetchMock.mockReset();
  getService.mockResolvedValue({ getResourceAreaLocation: () => Promise.resolve(""), getServiceLocation: () => Promise.resolve("") });
  vi.stubGlobal("fetch", fetchMock);
});

describe("authenticated attachment images", () => {
  it.each([
    ["preview object URLs", (host: AzureDevOpsWikiHostType, url: string) => host.loadImageObjectUrl(url)],
    ["draw.io data URLs", (host: AzureDevOpsWikiHostType, url: string) => host.loadImageDataUrl(url)],
  ])("rejects an author-controlled HTTPS URL from %s before requesting a bearer token", async (_path, load) => {
    const host = new AzureDevOpsWikiHost(CONTEXT);

    await expect(load(host, "https://attacker.example/collect")).rejects.toThrow(
      "only authenticate attachment URLs generated by this host"
    );

    expect(getAccessToken).not.toHaveBeenCalled();
    expect(fetchMock).not.toHaveBeenCalled();
  });

  it("rejects a changed path on an otherwise host-generated URL before requesting a token", async () => {
    const host = new AzureDevOpsWikiHost(CONTEXT);
    const generated = host.buildAttachmentUrl(WIKI, "/.attachments/diagram.drawio.png");
    const changed = new URL(generated ?? "https://invalid.example/");
    changed.searchParams.set("path", "/.attachments/another-file.png");

    await expect(host.loadImageObjectUrl(changed.href)).rejects.toThrow("only authenticate attachment URLs generated by this host");

    expect(getAccessToken).not.toHaveBeenCalled();
    expect(fetchMock).not.toHaveBeenCalled();
  });

  it("authenticates a Git Items URL generated by this host and rejects redirects", async () => {
    const host = new AzureDevOpsWikiHost(CONTEXT);
    const url = host.buildAttachmentUrl(WIKI, "/.attachments/diagram.drawio.png");
    getAccessToken.mockResolvedValue("reader-token");
    fetchMock.mockResolvedValue({ ok: false, status: 404 });

    await expect(host.loadImageDataUrl(url ?? "")).rejects.toThrow("Image fetch failed: 404");

    expect(getAccessToken).toHaveBeenCalledOnce();
    expect(fetchMock).toHaveBeenCalledWith(url, {
      headers: { Authorization: "Bearer reader-token" },
      redirect: "error"
    });
  });

  it.each([
    ["legacy Services", "https://org.visualstudio.com/PowerWiki/_git/Product.wiki"],
    ["Azure DevOps Server", "http://server/tfs/DefaultCollection/PowerWiki/_git/Product.wiki"],
  ])("continues to authenticate a host-generated URL on %s", async (_hostKind, repositoryRemoteUrl) => {
    const host = new AzureDevOpsWikiHost(CONTEXT);
    const url = host.buildAttachmentUrl({ ...WIKI, repositoryRemoteUrl }, "/.attachments/a.png");
    getAccessToken.mockResolvedValue("reader-token");
    fetchMock.mockResolvedValue({ ok: false, status: 404 });

    await expect(host.loadImageDataUrl(url ?? "")).rejects.toThrow("Image fetch failed: 404");

    expect(getAccessToken).toHaveBeenCalledOnce();
    expect(fetchMock).toHaveBeenCalledWith(url, expect.objectContaining({ redirect: "error" }));
  });
});
